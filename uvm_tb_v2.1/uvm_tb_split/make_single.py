#!/usr/bin/env python3
# ==============================================================================
#  make_single.py  -  build the EDA Playground single-file testbench
#  Author : Maharshi Oza (mmoza@ncsu.edu)
# ------------------------------------------------------------------------------
#  Reads the split testbench (this folder) and writes
#     ../uvm_tb_single/testbench.sv   every TB file pasted together, in compile
#                                     order, `include "..." lines replaced by the
#                                     file itself, all comments removed
#     ../uvm_tb_single/design.sv      only if missing: design/rtl + design/sva
#                                     pasted together (normally the already
#                                     verified combined file is kept)
#
#  The code is never edited by hand in the single version: fix the split files,
#  then run   python3 make_single.py
# ==============================================================================
import pathlib, re

HERE   = pathlib.Path(__file__).resolve().parent
TB     = HERE / "tb"
OUTDIR = HERE.parent / "uvm_tb_single"

TB_ORDER = [
    "common/cache_tb_defs.sv",
    "top/cache_if.sv",
    "pkg/cache_tb_pkg.sv",
    "top/tb_top.sv",
]

DESIGN_ORDER = [
    "design/rtl/cache_pkg.sv",
    "design/rtl/sram_sp.sv",
    "design/rtl/cache_tag_cmp.sv",
    "design/rtl/cache_lru.sv",
    "design/rtl/cache_lfu.sv",
    "design/rtl/cache_repl.sv",
    "design/rtl/cache_dirty.sv",
    "design/rtl/cache_ctrl.sv",
    "design/sva/cache_ctrl_sva.sv",
]

INC_RE = re.compile(r'^\s*`include\s+"([^"]+)"')


def strip_comment(line: str) -> str:
    """Remove a // comment that is not inside a string."""
    in_str = False
    i = 0
    while i < len(line) - 1:
        c = line[i]
        if c == '"' and (i == 0 or line[i - 1] != '\\'):
            in_str = not in_str
        elif not in_str and c == '/' and line[i + 1] == '/':
            return line[:i].rstrip()
        i += 1
    return line.rstrip()


def expand(path: pathlib.Path, out: list):
    out.append(f"// ---- {path.relative_to(TB)} ----")
    for raw in path.read_text().splitlines():
        m = INC_RE.match(raw)
        if m and m.group(1) != "uvm_macros.svh":
            expand(TB / m.group(1), out)
            continue
        if raw.strip().startswith("`timescale"):
            continue
        line = strip_comment(raw)
        if line.strip() == "" and raw.strip() != "":
            continue                      # line was only a comment
        out.append(line)


def squeeze_blank(lines):
    res, blank = [], False
    for l in lines:
        if l.strip() == "":
            if not blank:
                res.append("")
            blank = True
        else:
            res.append(l)
            blank = False
    return res


def main():
    OUTDIR.mkdir(exist_ok=True)

    body = []
    for f in TB_ORDER:
        expand(TB / f, body)
        body.append("")
    header = [
        "`timescale 1ns/1ps",
        "// =============================================================================",
        "//  cache_ctrl UVM testbench - SINGLE FILE (generated by make_single.py)",
        "//  Author : Maharshi Oza (mmoza@ncsu.edu)",
        "//  Do not edit: change the split files and regenerate.",
        "//  EDA Playground: UVM 1.2, Synopsys VCS. Default test: cache_smoke_test",
        "//  Run options: +UVM_TESTNAME=<test>  +NODUMP (no waves)",
        "// =============================================================================",
        "",
    ]
    (OUTDIR / "testbench.sv").write_text("\n".join(header + squeeze_blank(body)) + "\n")

    # design.sv: the combined RTL + SVA file that already passed on VCS is
    # kept as is. Only rebuild it (from design/) if it is missing.
    if not (OUTDIR / "design.sv").exists():
        design = ["`timescale 1ns/1ps", ""]
        for f in DESIGN_ORDER:
            design.append(f"// ==== {f} ====")
            for raw in (HERE / f).read_text().splitlines():
                if raw.strip().startswith("`timescale"):
                    continue
                design.append(raw.rstrip())
            design.append("")
        (OUTDIR / "design.sv").write_text("\n".join(design) + "\n")

    print("wrote", OUTDIR / "testbench.sv")
    print("wrote", OUTDIR / "design.sv")


if __name__ == "__main__":
    main()
